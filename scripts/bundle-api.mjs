// Bundle api/_cw.mjs and its CosmJS dependencies into one ESM file (api/_cwbundle.mjs).
// Why: Vercel's function loader cannot require() the ESM-only @noble/hashes from CosmJS's CommonJS build
// (ERR_REQUIRE_ESM, 2026-11-16). A single pre-bundled ESM file has no such require at runtime.
// Run after editing api/_cw.mjs:  node scripts/bundle-api.mjs   (the output is committed)
import { build } from "esbuild";
await build({
  entryPoints: ["api/_cw.mjs"], outfile: "api/_cwbundle.mjs", bundle: true, platform: "node", format: "esm",
  target: "node20", minify: true, legalComments: "eof",
  banner: { js: "// GENERATED by scripts/bundle-api.mjs from api/_cw.mjs. Do not edit.\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
});
console.log("api/_cwbundle.mjs built");
